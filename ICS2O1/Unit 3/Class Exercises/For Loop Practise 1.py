#This program will have a simple loop that will list the odd numbers of 1 through 9

def main():

    print('This program will print the odd numbers 1 through 9')
    
    #the for loop needs a variable to assign the values in the bracket
    #how a for loop works it that it assigns the first variable in the sequence, excecutes the block below
    #and then repeats it with the next thing in the sequence until it has gone through each number in the sequence
    #the bracket contains the odd numbers of 1-9
    for num in [1, 3, 5, 7, 9]:
        print(num)

main()
        

    
