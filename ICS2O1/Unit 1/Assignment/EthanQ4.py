#This program takes the input of 2 numbers (between 1-9) from the user
#It then calculates 5 different math operations for it
#The program then displays the outputs

#inputs for the 2 numbers
num1 = int(input('Enter the first number: '))
num2 = int(input('Enter the second number: '))

#calculations
add = num1 + num2
subtract = num1 - num2
multiply = num1 * num2
divide = num1 / num2
exponent = num1 ** num2

#output
print('the calculated answers are: ', add, ', ', subtract, ', ', multiply, ", ", divide, ' and ', exponent, sep = '')

