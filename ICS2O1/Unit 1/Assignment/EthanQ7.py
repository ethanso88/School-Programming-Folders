#This program will ask for the radius of a circle
#It will then calculate the circumference and area of the circle
#It will then display the answers as the output

#input
radius = int(input('What is the radius of the circle? '))

#calculation
circumference = 2 * 3.14 * radius 
area = 3.14 * (radius**2)

#output
print('The circumference is:', circumference,  '\n' \
      'The area is:', area)

