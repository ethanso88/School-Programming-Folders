#this program demonstrates what a
#variable reassignment is and how it works!

#First, we assign a value to the dollars variable
dollars = 2.75
print('I have $', dollars, 'in my account.')

#reassign the variable dollars so that 
#it references a new and different value than 2.75
dollars = 99.95
print('But now I have $', dollars, 'in my account!')


