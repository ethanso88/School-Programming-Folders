#This program also demonstrates PROPER coding formatting
#as well as using an escape character to print out new lines
#in one print function
print('Bur Oak Secondary School\n' \
      '933 Bur Oak Avenue\n' \
      'Markham, ON\n' \
      'L6E1G4\n')

#This demonstrates how to print double quotation marks in a string
print("Don't fear!\n\n" \
      'My name is "Mrs. Biswas".\n')

#This demonstrates how to print a line with both quotations in it
print("""Don't fear! My name is "Mrs. Biswas".""")
print('''Don't fear! My name is "Mrs. Biswas".''')
